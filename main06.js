// Escreva um programa que verifique se um número fornecido pelo usuário é positivo, negativo ou zero.

var numero = 13

if ( numero > 0 ) {
    console.log("Seu numero é positivo -> " + numero)
} else if ( numero == 0 ) {
    console.log("Seu numero é igual a zero -> " + numero)
} else {
    console.log("Seu numero é negativo -> " + numero)
}